    + node(95, 150, '미리 주문', { role: 'x', rx: 46 })
    + node(255, 150, '대기 시간', { role: 'y', rx: 46 })
    + tag(175, 212, '옆 사람의 주문은 내 대기에 닿지 않는다')
    + panel(370, 55, 310, 180)
    + caseTitle(525, 42, '전원에게 열 때')
    + edge(445, 180, 605, 180, { from: 46, to: 46, tone: 's1' })
    + edge(480, 92, 605, 180, { from: 54, to: 46 })
    + node(480, 92, '남들의 주문', { rx: 54 })
    + node(445, 180, '미리 주문', { role: 'x', rx: 46 })
    + node(605, 180, '대기 시간', { role: 'y', rx: 46 })
    + tag(525, 224, '남들이 함께 주문하면 내 대기가 달라진다')
    + caseTitle(350, 264, '오른쪽에 화살표가 하나 늘었다. 5장이 그것을 간섭이라 불렀다')
    + caseTitle(350, 290, '작게 잰 값이 크게 해도 그대로일 이유가 없다');

/* ── 3. 나눌 방법이 많다 ───────────────────────────────────────── */

const ROWS = [
    { name: '나누지 않고 전체', cells: ['0.10'] },
    { name: '부서로 나눔', cells: ['0.12', '0.08'] },
    { name: '연차로 나눔', cells: ['0.09', '0.11'] },
    { name: '점심 시각으로 나눔', cells: ['0.02', '0.31'] },
];

const subgroup = caseTitle(360, 40, '같은 자료를 여러 기준으로 나눠 본 값')
    + ROWS.map((r, i) => {
        const y = 85 + i * 55;
        const label = txt(30, y + 4, r.name, { size: 'sm', cls: 'ink2' });
        if (r.cells.length === 1) {
            return label + panel(250, y - 20, 320, 40) + tag(410, y + 4, r.cells[0]);
        }
        return label
            + panel(250, y - 20, 150, 40) + tag(325, y + 4, r.cells[0])
            + panel(420, y - 20, 150, 40) + tag(495, y + 4, r.cells[1]);
    }).join('')
    + tag(648, 254, '여기가 눈에 띈다')
    + caseTitle(360, 292, '나눌 방법이 늘어나면 크게 나온 칸이 하나쯤 생긴다');

/* ── 4. 좁아진 자리들이 한자리에 모인다 ────────────────────────── */

const NARROW = [
    { x: 45, name: '도구변수가 답하는 자리', who: '순응자', note: '누구인지 자료로 가릴 수 없다' },
    { x: 262, name: '잘라내기 뒤 남는 자리', who: '겹치는 구간', note: '점수로만 적힌다' },
    { x: 479, name: '회귀 불연속의 자리', who: '기준값 근처', note: '멀리 있는 대상은 빠진다' },
];

const narrow = panel(20, 60, 680, 175)
    + caseTitle(360, 48, '물으려던 대상 — 전체')
    + NARROW.map((c) =>
        panel(c.x, 95, 195, 115)
        + caseTitle(c.x + 97, 122, c.name)
        + tag(c.x + 97, 150, c.who)
        + tag(c.x + 97, 176, c.note)).join('')
    + caseTitle(360, 264, '이름은 셋 다 다른데 답하는 자리가 좁아졌다는 점은 같다')
    + caseTitle(360, 292, '가정이 약해질수록 자리가 좁아진다');

/* ── 5. 예측이 기대고 있던 화살표를 개입이 끊는다 ──────────────── */

