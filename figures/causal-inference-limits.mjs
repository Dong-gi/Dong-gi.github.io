/**
 * 이 도구들이 못 하는 것 장 그림. 원장 §5.2 의 규약을 따른다.
 *
 *   - 처치는 왼쪽, 결과는 오른쪽
 *   - 통제한 변수는 상자, 관측되지 않은 변수는 점선 원
 *   - 열린 경로는 실선, 막힌 경로는 회색 점선
 *   - 노드 이름은 짧은 한국어. SVG 안에는 수식을 쓸 수 없다
 *
 * 이 장은 한계를 그린다. 그래서 그림 대부분이 '무엇이 자료로 채워지고 무엇이
 * 채워지지 않는가'를 두 칸으로 갈라 놓는 모양이다. 마디·화살표·칸·딱지는 모두
 * graph-lib 의 함수로 그려서 앞 장들과 규약이 갈리지 않게 한다.
 *
 * 색의 뜻을 이 장 전체에서 고정한다.
 *   s1 — 처치, 그리고 재려던 인과 경로
 *   s2 — 결과
 * 색만으로 구분하지 않도록 모든 칸과 선에 이름을 함께 적는다(규격 §4).
 */
import { svg, txt } from './lib.mjs';
import { node, edge, tag, caseTitle, panel } from './causal-inference-graph-lib.mjs';

/* ── 1. 답을 다른 자리로 옮기는 일 ─────────────────────────────── */

const HERE = ['이 사람들', '이 시기', '이 규모', '이 방식'];
const THERE = ['다른 사람들', '다른 시기', '다른 규모', '다른 방식'];

const transport = panel(20, 65, 250, 175)
    + caseTitle(145, 52, '실험이 답한 자리')
    + HERE.map((t, i) => tag(145, 105 + i * 35, t)).join('')
    + panel(450, 65, 250, 175)
    + caseTitle(575, 52, '옮기려는 자리')
    + THERE.map((t, i) => tag(575, 105 + i * 35, t)).join('')
    + edge(270, 152, 450, 152, { from: 6, to: 6, tone: 's1' })
    + tag(360, 130, '새 가정')
    + caseTitle(360, 270, '가운데 화살표를 놓아 주는 것은 자료가 아니라 새 가정이다')
    + caseTitle(360, 296, '실험이 아무리 잘되어도 그 화살표는 실험 안에 없다');

/* ── 2. 규모가 바뀌면 화살표가 하나 늘어난다 ───────────────────── */

const scale = panel(20, 55, 310, 180)
