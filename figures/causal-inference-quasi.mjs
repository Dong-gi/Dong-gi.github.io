/**
 * 준실험 설계 장 그림. 원장 §5.2 의 규약을 따른다.
 *
 *   - 처치는 왼쪽, 결과는 오른쪽
 *   - 통제한 변수는 상자, 관측되지 않은 변수는 점선 원
 *   - 열린 경로는 실선, 막힌 경로는 회색 점선
 *   - 노드 이름은 짧은 한국어. SVG 안에는 수식을 쓸 수 없다
 *
 * 이 장의 본체는 인과 그래프가 아니라 시간선이다. 꺾은선은 여기서 직접 그리되
 * 칸·딱지·소제목·노드·화살표는 다른 장과 같게 보이도록 graph-lib 의 것을 쓴다.
 *
 * 색의 뜻을 그림 전체에서 고정한다.
 *   s1 — 처치집단, 그리고 처치집단에 대한 반사실
 *   s2 — 대조집단, 그리고 기준 위쪽(처치를 받지 않는 쪽)
 *   s3 — 자료에 보이지 않는 것. 실제 반사실, 끊긴 크기
 * 색만으로 구분하지 않도록 모든 선에 이름을 함께 적는다(규격 §4).
 */
import { svg } from './lib.mjs';
import { node, edge, tag, caseTitle, panel } from './causal-inference-graph-lib.mjs';

const round = (v) => Number.parseFloat(v.toFixed(2));

/** 시간선 한 도막. 값은 화소 y 로 직접 준다. */
const seg = (x1, y1, x2, y2, tone, dash) =>
    `<path d="M${round(x1)} ${round(y1)} L${round(x2)} ${round(y2)}" fill="none"`
    + ` stroke="var(--${tone})" stroke-width="2.4" stroke-linecap="round"`
    + `${dash ? ` stroke-dasharray="${dash}"` : ''}/>`;

/** 점 여럿을 잇는 꺾은선. */
const poly = (pts, tone, dash) =>
    `<path d="M${pts.map(([a, b]) => `${round(a)} ${round(b)}`).join(' L')}" fill="none"`
    + ` stroke="var(--${tone})" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round"`
    + `${dash ? ` stroke-dasharray="${dash}"` : ''}/>`;

const pt = (x, y, tone) =>
    `<circle cx="${round(x)}" cy="${round(y)}" r="4.5" fill="var(--${tone})"/>`;

const dots = (pts, tone) => pts.map(([a, b]) => pt(a, b, tone)).join('');

/** 축이나 이음선. */
const rule = (x1, y1, x2, y2) =>
    `<path d="M${x1} ${y1} L${x2} ${y2}" stroke="var(--ink2)" stroke-width="1.2" fill="none"/>`;

/** 옅은 보조선. */
const guide = (x1, y1, x2, y2) =>
    `<path d="M${x1} ${y1} L${x2} ${y2}" stroke="var(--grid)" stroke-width="1"`
    + ` stroke-dasharray="4 3" fill="none"/>`;

/** 세로 간격 표시. 자료에 보이지 않는 크기를 가리킬 때 쓴다. */
const gapMark = (x, y1, y2) =>
    `<path d="M${x} ${y1} L${x} ${y2}" stroke="var(--s3)" stroke-width="3.5"`
    + ` stroke-linecap="round" fill="none"/>`;

/** 도수 막대. */
const bar = (x, base, w, h, tone) => (h <= 0 ? ''
    : `<rect x="${round(x)}" y="${round(base - h)}" width="${w}" height="${round(h)}" rx="1"`
      + ` fill="var(--${tone})" fill-opacity="0.5" stroke="var(--${tone})" stroke-width="1.2"/>`);

