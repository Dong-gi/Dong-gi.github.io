/**
 * 도구변수 장 그림. 원장 §5.2 의 규약을 따른다.
 *
 *   - 처치는 왼쪽, 결과는 오른쪽. 예외를 두지 않는다
 *   - 통제한 변수는 상자, 관측되지 않은 변수는 점선 원
 *   - 열린 경로는 실선, 막힌 경로는 회색 점선
 *   - 노드 이름은 짧은 한국어. SVG 안에는 수식을 쓸 수 없다
 *
 * 이 장은 못 잰 혼입변수를 그대로 둔 채 그림을 그린다. 그래서 점선 원이 거의 모든
 * 그림에 나오고, 그 원에서 나가는 화살표는 막히지 않은 채로 남는다. 그것이 이 장의
 * 출발점이므로 지우지 않는다.
 *
 * 화살표 색의 뜻을 그림 전체에서 고정한다.
 *   s1 — 도구가 처치를 흔드는 화살표, 그리고 재려는 인과 경로
 *   s2 — 막대 그림에서 도구가 0 인 쪽 (s1 이 도구가 1 인 쪽)
 *   s3 — 막지 못한 뒷문, 그리고 조건을 깨뜨리는 화살표
 * 색만으로 구분하지 않도록 모든 마디와 막대에 이름을 함께 적는다(규격 §4).
 */
