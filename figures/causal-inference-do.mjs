/**
 * 보는 것과 바꾸는 것 장 그림. 원장 §5.2 의 규약을 따른다.
 *
 *   - 처치는 왼쪽, 결과는 오른쪽. 예외를 두지 않는다
 *   - 열린 화살표는 실선
 *   - 노드 이름은 짧은 한국어. SVG 안에는 수식을 쓸 수 없다
 *
 * 이 장에는 통제한 변수도 관측되지 않은 변수도 없다. 상자(boxed)는 9장부터,
 * 점선 원(unobserved)은 그보다 뒤에 나오므로 여기서는 쓰지 않는다.
 *
 * 이 장의 중심 그림은 ci-d-cut 이다. 개입이 무엇을 바꾸는지를 그림 하나로
 * 보이는 자리이고, 나머지 그림들은 그 앞뒤를 받쳐 준다. 막힌 경로를 뜻하는
 * 회색 점선(blocked)을 여기서 쓰지 않은 것은 일부러다 — 8장이 그 표시에
 * 다른 뜻을 준다. 끊긴 화살표는 그리지 않고 딱지로만 알린다.
 */
import { svg } from './lib.mjs';
import { node, edge, tag, caseTitle, panel } from './causal-inference-graph-lib.mjs';

/* 노드 이름이 길어 반지름을 직접 주는 자리들. edge 에 같은 값을 넘겨야
   화살표가 노드를 파고들지 않는다. */
const R_SET = 70;   // '처치를 정하던 것'
const R_ARM = 53.2; // 여섯 글자짜리 이름
const R_OUT = 26;   // '처치' · '결과'

/* ── 1. 같은 자료 앞에서 물을 수 있는 두 가지 ───────────────── */

const twoQuestions = panel(15, 45, 330, 155)
    + caseTitle(180, 34, '보는 물음')
    + node(110, 105, '처치받은 쪽', { role: 'x', rx: R_ARM })
    + node(265, 105, '결과', { role: 'y' })
    + edge(110, 105, 265, 105, { from: R_ARM, to: R_OUT, tone: 's1' })
    + tag(180, 162, '이미 있는 자료에서 골라낸다')
    + tag(180, 184, '자료가 답해 준다')

    + panel(370, 45, 315, 155)
    + caseTitle(527, 34, '바꾸는 물음')
    + node(455, 105, '모두에게 처치', { role: 'x', rx: 60.4 })
    + node(610, 105, '결과', { role: 'y' })
    + edge(455, 105, 610, 105, { from: 60.4, to: R_OUT, tone: 's2' })
    + tag(527, 162, '그런 세상은 자료에 없다')
    + tag(527, 184, '가정이 있어야 답이 나온다')

    + caseTitle(350, 232, '같은 자료 앞에서 물을 수 있는 두 가지이고 답이 서로 다르다');

/* ── 2. 고르는 일과 정하는 일 ───────────────────────────────── */

const selectVsSet = panel(15, 45, 320, 150)
    + caseTitle(175, 34, '고른다')
    + node(100, 110, '모든 대상', { rx: 46 })
    + node(255, 110, '처치받은 쪽', { role: 'x', rx: R_ARM })
    + edge(100, 110, 255, 110, { from: 46, to: R_ARM })
    + tag(175, 165, '자료에서 일부만 남긴다')
    + tag(175, 187, '세상은 그대로다')

    + panel(365, 45, 320, 150)
    + caseTitle(525, 34, '정한다')
    + node(450, 110, '모든 대상', { rx: 46 })
    + node(605, 110, '모두 처치', { role: 'x', rx: 46 })
    + edge(450, 110, 605, 110, { from: 46, to: 46, tone: 's2' })
    + tag(525, 165, '값을 우리가 넣는다')
    + tag(525, 187, '세상이 달라진다')

    + caseTitle(350, 228, '왼쪽은 자료를 나누는 일이고 오른쪽은 자료를 만드는 일이다');

/* ── 3. 이 장의 중심 그림 — 개입은 처치로 들어오던 화살표를 끊는다 ── */

const cut = panel(15, 50, 330, 200)
    + caseTitle(180, 38, '관찰 — 그대로 두고 본다')
    + node(180, 95, '처치를 정하던 것', { rx: R_SET })
    + node(85, 190, '처치', { role: 'x' })
    + node(275, 190, '결과', { role: 'y' })
    + edge(180, 95, 85, 190, { from: R_SET, to: R_OUT })
    + edge(180, 95, 275, 190, { from: R_SET, to: R_OUT })
    + edge(85, 190, 275, 190, { from: R_OUT, to: R_OUT, tone: 's1' })
    + tag(180, 236, '처치로 화살표가 들어온다')

    + panel(375, 50, 330, 200)
    + caseTitle(540, 38, '개입 — 우리가 정한다')
    + node(540, 95, '처치를 정하던 것', { rx: R_SET })
    + node(445, 190, '처치', { role: 'x' })
    + node(635, 190, '결과', { role: 'y' })
    + edge(540, 95, 635, 190, { from: R_SET, to: R_OUT })
    + edge(445, 190, 635, 190, { from: R_OUT, to: R_OUT, tone: 's1' })
    + tag(452, 148, '화살표가 없다')
    + tag(540, 236, '처치는 우리가 넣은 값이다')

    + caseTitle(360, 288, '두 그림의 차이는 처치로 들어오는 화살표 하나뿐이다');

/* ── 4. 개입이 하나로 정해지는가 ────────────────────────────── */

const wellDefined = panel(10, 45, 232, 150)
