    + tag(126, 152, '무엇을 하는 일인지')
    + tag(126, 174, '손으로 가리킬 수 있다')

    + panel(254, 45, 232, 150)
    + caseTitle(370, 34, '여러 가지다')
    + node(370, 100, '교육을 늘린다', { role: 'x' })
    + tag(370, 152, '수업을 늘리는 것과')
    + tag(370, 174, '학교를 더 다니는 것이 다르다')

    + panel(498, 45, 232, 150)
    + caseTitle(614, 34, '상상하기 어렵다')
    + node(614, 100, '타고난 특성을 바꾼다', { role: 'x' })
    + tag(614, 152, '무엇을 하는 일인지')
    + tag(614, 174, '정해지지 않는다')

