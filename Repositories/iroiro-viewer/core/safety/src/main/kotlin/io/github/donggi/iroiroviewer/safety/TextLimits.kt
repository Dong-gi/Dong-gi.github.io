package io.github.donggi.iroiroviewer.safety

/**
 * 텍스트 뷰어의 상한. **순수 함수와 상수뿐이다.**
 *
 * ## [ParseLimits] 와 따로 두는 이유
 *
 * [ParseLimits] 는 *신뢰할 수 없는 입력*에서 우리를 지키는 상한이다(압축 폭탄, 무한 중첩).
 * 이쪽은 성격이 다르다 — 사용자의 200 MB 로그 파일은 악의가 없는데도 메모리에 안 들어간다.
 * 막아야 할 것이 공격이 아니라 **산수**라는 점에서 [ImageLimits] 와 같은 자리다.
 *
 * ## 파일 크기 상한을 두지 않는다
 *
 * 흔한 선택은 "50 MB 넘으면 못 엽니다" 인데, 그것은 **설계를 못 한 것을 사용자에게
 * 떠넘기는 것**이다. 이 앱은 모든 파일 접근 권한을 가지고 사용자의 logcat 덤프를 연다.
 * 창 단위로 읽고 성긴 색인만 들면 파일 크기는 비용이 아니다 — 남는 유일한 비용은
 * 색인 시간이고, 그것은 취소할 수 있으면 문제가 아니다.
 */
object TextLimits {

    /**
     * 한 행에 담는 최대 글자 수. **상한이 아니라 분할 단위다.**
     *
     * 줄바꿈이 없는 480 KB 짜리 미니파이 JS 가 실재한다. 그런 줄을 거부하면 "열 수
     * 없습니다" 가 되고, 통째로 한 행에 넣으면 그 한 행을 그리다 화면이 멎는다.
     * 그래서 **자른다** — 사용자에게는 여러 줄로 보이고, 줄 번호는 논리 줄을 가리킨다.
     */
    const val SEGMENT_CHARS = 4_096

    /**
     * 앵커를 찍는 간격. **둘 중 먼저 오는 쪽**이다.
     *
     * 바이트만 보면 줄이 짧은 파일에서 앵커가 너무 촘촘해지고, 행만 보면 한 줄이 긴
     * 파일에서 되읽기가 길어진다. 둘을 함께 걸면 되읽기가 **64 KiB + 한 행**으로 묶인다.
     */
    const val ANCHOR_BYTES = 64 * 1024
    const val ANCHOR_ROWS = 256

    /** 한 번에 읽는 바이트. 판정 창과 같은 크기로 맞춰 읽기를 한 번 줄인다. */
    const val WINDOW_BYTES = 64 * 1024

    /**
     * 문법 강조를 켜는 파일 크기 상한.
     *
     * 강조는 **행마다 시작 상태**를 들고 있어야 해서(여러 줄 주석·여러 줄 문자열) 색인이
     * 바이트 주사가 아니라 디코드 패스가 된다. 큰 파일에서 그 비용이 색인 시간을 몇 배로
     * 만든다. 넘으면 강조를 끄고 화면이 그렇게 말한다.
     *
     * **이 값은 기기에서 재기 전까지 근거가 약하다.** 진단 화면의 처리량 측정이 끝나면
     * 여기를 고친다.
     */
    const val HIGHLIGHT_MAX_BYTES = 4L * 1024 * 1024

    /** 찾기 결과를 이만큼만 모은다. 더 찾아 봐야 사람이 훑을 수 없다. */
    const val MAX_SEARCH_HITS = 10_000

    /**
     * 이 행 수마다 색인 진행을 알린다. 너무 잦으면 알리는 것이 일이 된다.
     */
    const val PROGRESS_EVERY_ROWS = 20_000

    /**
     * 앵커 하나가 차지하는 바이트. 성긴 색인의 메모리를 셈할 때 쓴다.
     *
     * `Long`(바이트 오프셋) + `Int`(행) + `Int`(논리 줄) = 16바이트.
     */
    const val ANCHOR_BYTES_IN_MEMORY = 16

    /**
     * 이 파일에 앵커가 몇 개나 생기는가(대략).
     *
     * 1 GB·1천만 행이면 약 55,000개 × 16바이트 ≈ **0.9 MB** 다. 줄마다 오프셋을 들면
     * 같은 파일이 76 MB 이므로, 성기게 두는 것만으로 메모리가 논점에서 빠진다.
     */
    fun estimateAnchors(fileBytes: Long, rows: Long): Long =
        fileBytes / ANCHOR_BYTES + rows / ANCHOR_ROWS + 1
}
