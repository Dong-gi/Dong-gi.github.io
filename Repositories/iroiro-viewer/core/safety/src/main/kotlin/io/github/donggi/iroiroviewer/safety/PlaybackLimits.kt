package io.github.donggi.iroiroviewer.safety

/**
 * 재생 목록의 상한. **방어 상한은 `core:safety` 한곳에 모은다**(저장소 규칙).
 *
 * 여기 있는 것은 '악의적인 파일' 이 아니라 **평범하지만 아주 큰 폴더**를 막는 값이다.
 * 음악 폴더에 1만 개가 있는 것은 흔한 일이고, 그 전부를 큐로 만들면 `MediaItem` 1만 개가
 * 프로세스를 넘어 세션으로 건너간다(`Binder` 트랜잭션은 1 MB 근처에서 죽는다).
 */
object PlaybackLimits {

    /**
     * 한 큐에 담는 항목 수.
     *
     * **왜 500인가.** `MediaItem` 하나가 경로·제목·미디어ID 를 들고 있어 직렬화하면
     * 수백 바이트다. 500개면 넉넉잡아 200 KB 안쪽이라 `Binder` 의 1 MB 에서 멀다.
     * 그리고 사람이 한 폴더에서 이어 듣는 양의 상한으로도 충분하다 — 넘으면 그 폴더는
     * '앨범' 이 아니라 '보관함' 이다.
     *
     * **상한을 넘으면 자르되, 사용자가 누른 항목은 반드시 담는다**
     * ([io.github.donggi.iroiroviewer.playback] 의 `FolderQueue` 참고). 누른 것이 빠지면
     * 다른 파일이 재생되고, 그것은 '내가 고른 것과 다른 것이 열린다' 는 이 저장소가
     * 8단계에서 치명으로 고친 형태다.
     */
    const val MAX_QUEUE_ITEMS = 500
}
